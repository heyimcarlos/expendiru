import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  monthlyBucketWire,
  parseMonthlyByBucketCsv,
  monthlyRowsFromDollars,
} from "../packages/domain/src/spend.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const feedDir = process.env.EXPENDIRU_FEED ?? "/workspace/finance/expendiru-feed";
const transactionsPath = join(feedDir, "transactions.json");
const summaryPath = join(feedDir, "summary.json");
const monthlyPath = join(feedDir, "monthly_by_bucket.csv");
const monthlyJsonPath = join(feedDir, "monthly_by_bucket.json");
const out = join(root, "packages/backend/src/spend.generated.ts");

if (!existsSync(transactionsPath) || !existsSync(summaryPath)) {
  console.log(`No feed at ${feedDir}. Leaving the spend payload unchanged.`);
  process.exit(0);
}

const transactions = JSON.parse(readFileSync(transactionsPath, "utf8"));
const summary = JSON.parse(readFileSync(summaryPath, "utf8"));

if (!Array.isArray(transactions)) {
  console.error(`${transactionsPath} is not an array`);
  process.exit(1);
}

if (typeof summary.as_of !== "string" || summary.period == null) {
  console.error(`${summaryPath} is missing period or as_of`);
  process.exit(1);
}

const payload = {
  period: summary.period,
  as_of: summary.as_of,
  transactions,
};

const readMonthly = () => {
  if (existsSync(monthlyPath)) {
    return {
      file: monthlyPath,
      parsed: parseMonthlyByBucketCsv(readFileSync(monthlyPath, "utf8")),
    };
  }

  if (!existsSync(monthlyJsonPath)) {
    return undefined;
  }

  const json = JSON.parse(readFileSync(monthlyJsonPath, "utf8"));
  const months = json?.months;

  if (!Array.isArray(months)) {
    return {
      file: monthlyJsonPath,
      parsed: {
        ok: false,
        error: "monthly_by_bucket.json needs a months array",
      },
    };
  }

  return { file: monthlyJsonPath, parsed: monthlyRowsFromDollars(months) };
};

const monthly = readMonthly();

if (monthly !== undefined) {
  const parsed = monthly.parsed;
  const monthlyFile = monthly.file;

  if (!parsed.ok) {
    console.error(parsed.error);
    process.exit(1);
  }

  payload.monthly_by_bucket = monthlyBucketWire(parsed.rows);
  console.log(`Read ${parsed.rows.length} months from ${monthlyFile}`);
}

const source = [
  "// Generated by scripts/sync-spend-feed.mjs from the Household Finance feed.",
  "// Gitignored. Do not commit.",
  `export const encodedSpendGenerated = ${JSON.stringify(payload)}`,
  "",
].join("\n");

writeFileSync(out, source);
console.log(`Wrote ${transactions.length} transactions to ${out}`);
